import test from 'node:test';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
test('preview scrolls independently and accepts local scroll only from its parent', async () => {
 const events={},messages=[],scrolls=[];
 const parent={postMessage:message=>messages.push(message)};
 const window={parent,scrollBy:(_,delta)=>scrolls.push(delta)};
 const style={};
 const context={window,parent,document:{documentElement:{style}},addEventListener:(name,fn)=>events[name]=fn};
 vm.runInNewContext(await readFile(new URL('../public/preview-bridge.js',import.meta.url),'utf8'),context);
 const send=(data,source=parent)=>events.message({source,data});
 send({type:'portfolio:mode',containScroll:true});
 assert.equal(style.overscrollBehaviorY,'contain');
 send({type:'portfolio:scroll',ratio:.9});
 send({type:'portfolio:local-scroll',delta:100},{});
 send({type:'portfolio:local-scroll',delta:Infinity});
 assert.deepEqual(scrolls,[]);
 assert.equal(events.wheel,undefined);
 send({type:'portfolio:local-scroll',delta:80});
 assert.deepEqual(scrolls,[80]);
 send({type:'portfolio:mode',containScroll:false});
 assert.equal(style.overscrollBehaviorY,'auto');
 send({type:'portfolio:mode',expanded:true,containScroll:true});
 events.keydown({key:'Escape'});
 assert.equal(messages.at(-1).type,'portfolio:close');
});
